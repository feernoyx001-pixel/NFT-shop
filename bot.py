# WEBHOOK-РЕЖИМ (для Render и подобных хостингов)
# ============================================================
# Отличие от long polling: тут не бот сам спрашивает Telegram
# "есть что новое?", а Telegram сам стучится на наш адрес, когда
# приходит сообщение. Это нужно на хостингах, где нельзя держать
# вечный цикл (например, бесплатный тариф Render).

try:
    from flask import Flask, request as flask_request, jsonify
    _FLASK_AVAILABLE = True
except ImportError:
    _FLASK_AVAILABLE = False

if _FLASK_AVAILABLE:
    app = Flask(__name__)

    @app.route("/", methods=["GET"])
    def health_check():
        # Этот адрес нужен, чтобы внешний "будильник" (UptimeRobot и т.п.)
        # мог стучаться сюда каждые несколько минут и не давать
        # бесплатному серверу Render засыпать.
        return "OK, bot is alive", 200

    @app.route(f"/webhook/<token>", methods=["POST"])
    def telegram_webhook(token):
        if token != BOT_TOKEN:
            return "forbidden", 403
        update = flask_request.get_json(force=True, silent=True) or {}
        # обрабатываем в отдельном потоке, чтобы сразу ответить Telegram
        # 200 OK — иначе Telegram может посчитать вебхук неотвечающим
        threading.Thread(target=process_update, args=(update,), daemon=True).start()
        return jsonify(ok=True)


def set_webhook():
    external_url = os.environ.get("RENDER_EXTERNAL_URL", "").rstrip("/")
    if not external_url:
        logger.warning("RENDER_EXTERNAL_URL не задан — установите вручную "
                        "переменную окружения WEBHOOK_URL с адресом вашего "
                        "сервиса на Render (например https://имя.onrender.com)")
        external_url = os.environ.get("WEBHOOK_URL", "").rstrip("/")
        if not external_url:
            logger.error("Не удалось определить внешний адрес — webhook НЕ установлен.")
            return
    webhook_url = f"{external_url}/webhook/{BOT_TOKEN}"
    resp = api_call("setWebhook", url=webhook_url)
    if resp.get("ok"):
        logger.info(f"Webhook установлен: {webhook_url}")
    else:
        logger.error(f"Не удалось установить webhook: {resp}")


def run_webhook_mode():
    if not _FLASK_AVAILABLE:
        logger.error("Flask не установлен! Выполните: pip install flask")
        return
    init_db()
    setup_bot_commands()
    set_webhook()
    logger.info("Бот запущен в РЕЖИМЕ WEBHOOK (для Render).")
    if ADMIN_ID:
        logger.info(f"Админ-панель активна для user_id={ADMIN_ID}")
    port = int(os.environ.get("PORT", 10000))
    app.run(host="0.0.0.0", port=port, threaded=True)


if __name__ == "__main__":
    # Если запущено на Render (или явно попросили webhook-режим) —
    # используем webhook. Иначе (Termux, обычный сервер) — старый
    # режим long polling, как раньше.
    use_webhook = bool(os.environ.get("RENDER")) or os.environ.get("USE_WEBHOOK") == "1"
    if use_webhook:
        run_webhook_mode()
    else:
        main()
