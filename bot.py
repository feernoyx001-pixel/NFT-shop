def process_update(u):
    """Обрабатывает один апдейт в отдельном потоке, чтобы медленный
    whois/HIBP-запрос не блокировал ответы другим пользователям."""
    try:
        if "message" in u:
            handle_message(u["message"])
        elif "callback_query" in u:
            handle_callback(u["callback_query"])
    except Exception as e:
        logger.error(f"Ошибка обработки апдейта: {e}")
        # пытаемся уведомить пользователя, если удаётся достать chat_id
        try:
            chat_id = None
            if "message" in u:
                chat_id = u["message"]["chat"]["id"]
            elif "callback_query" in u:
                chat_id = u["callback_query"]["message"]["chat"]["id"]
            if chat_id:
                send(chat_id, "⚠️ Произошла ошибка при обработке. Попробуйте /start.")
        except Exception:
            pass


