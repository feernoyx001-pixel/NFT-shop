def main():
    init_db()
    setup_bot_commands()
    logger.info("Бот запущен (многопоточный режим, long polling). Ctrl+C для остановки.")
    if ADMIN_ID:
        logger.info(f"Админ-панель активна для user_id={ADMIN_ID}")
    else:
        logger.info("Админ не настроен. Отправьте /myid в бота, затем задайте ADMIN_ID.")
    offset = None
    executor = ThreadPoolExecutor(max_workers=8)
    while True:
        try:
            params = {"timeout": 30}
            if offset:
                params["offset"] = offset
            r = requests.get(API_URL + "getUpdates", params=params, timeout=40)
            data = r.json()
            if not data.get("ok"):
                logger.warning(f"Ошибка Telegram API: {data}")
                if "Conflict" in str(data.get("description", "")):
                    logger.warning("‼️ Запущено НЕСКОЛЬКО копий бота. Выполните: pkill -9 -f bot.py")
                time.sleep(3)
                continue
            updates = data.get("result", [])
            for u in updates:
                offset = u["update_id"] + 1
                executor.submit(process_update, u)
        except requests.exceptions.RequestException as e:
            logger.warning(f"Сетевая ошибка, повтор через 5 сек: {e}")
            time.sleep(5)
        except KeyboardInterrupt:
            logger.info("Остановлено пользователем.")
            break


