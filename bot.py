def api_call(method, **params):
    try:
        r = requests.post(API_URL + method, json=params, timeout=40)
        return r.json()
    except Exception as e:
        logger.error(f"api_call({method}) ошибка: {e}")
        return {"ok": False, "description": str(e)}


def send(chat_id, text, inline_kb=None, reply_keyboard=None):
    # Telegram режет сообщения длиннее ~4096 символов — большие отчёты шлём файлом
    if len(text) > 3500:
        return send_document(chat_id, "report.txt", text, inline_kb)
    params = {"chat_id": chat_id, "text": text}
    if reply_keyboard is not None:
        params["reply_markup"] = json.dumps(reply_keyboard)
    elif inline_kb:
        params["reply_markup"] = json.dumps({"inline_keyboard": inline_kb})
    return api_call("sendMessage", **params)


def send_document(chat_id, filename, text_content, inline_kb=None):
    try:
        files = {"document": (filename, text_content.encode("utf-8"), "text/plain")}
        data = {"chat_id": chat_id, "caption": "📄 Отчёт (слишком длинный для сообщения)"}
        if inline_kb:
            data["reply_markup"] = json.dumps({"inline_keyboard": inline_kb})
        r = requests.post(API_URL + "sendDocument", data=data, files=files, timeout=40)
        return r.json()
    except Exception as e:
        logger.error(f"send_document ошибка: {e}")
        return None


def edit(chat_id, message_id, text, inline_kb=None):
    if len(text) > 3500:
        # длинный текст нельзя вставить в edit — шлём отдельным файлом
        send_document(chat_id, "report.txt", text, inline_kb)
        return
    params = {"chat_id": chat_id, "message_id": message_id, "text": text}
    if inline_kb:
        params["reply_markup"] = json.dumps({"inline_keyboard": inline_kb})
    return api_call("editMessageText", **params)


