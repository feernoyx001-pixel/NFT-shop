def whois_lookup(domain):
    domain = domain.strip().lower()
    try:
        with socket.create_connection(("whois.iana.org", 43), timeout=6) as s:
            s.send((domain + "\r\n").encode())
            data = b""
            while True:
                chunk = s.recv(4096)
                if not chunk:
                    break
                data += chunk
        text = data.decode(errors="ignore")
        m = re.search(r"refer:\s*(\S+)", text)
        if not m:
            return "WHOIS-сервер для этой зоны не найден."
        refer = m.group(1)
        with socket.create_connection((refer, 43), timeout=6) as s:
            s.send((domain + "\r\n").encode())
            data = b""
            while True:
                chunk = s.recv(4096)
                if not chunk:
                    break
                data += chunk
        result = data.decode(errors="ignore")
        lines = [l for l in result.splitlines() if l.strip() and not l.startswith("%") and not l.startswith("#")]
        return "WHOIS " + domain + ":\n" + "\n".join(lines[:15])
    except Exception as e:
        return f"Ошибка WHOIS: {e}"


def ip_lookup(target):
    try:
        ip = socket.gethostbyname(target)
    except socket.gaierror:
        return "Не удалось определить IP."
    try:
        r = requests.get(f"https://ipapi.co/{ip}/json/", timeout=6)
        d = r.json()
        if d.get("error"):
            return f"IP: {ip}"
        return (f"IP: {ip}\nСтрана: {d.get('country_name','—')}\n"
                f"Город: {d.get('city','—')}\nПровайдер: {d.get('org','—')}")
    except Exception as e:
        return f"IP: {ip}\nОшибка гео-данных: {e}"


