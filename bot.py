CACHE = {}          # (action, target) -> (timestamp, result_text)
CACHE_TTL = 300      # 5 минут
LAST_ACTION = {}     # user_id -> timestamp последнего инструмента
MIN_INTERVAL = 3     # секунд между запросами к инструментам


def cache_get(action, target):
    key = (action, target.lower())
    item = CACHE.get(key)
    if item and time.time() - item[0] < CACHE_TTL:
        return item[1]
    return None


def cache_set(action, target, value):
    CACHE[(action, target.lower())] = (time.time(), value)


def rate_limited(user_id):
    now = time.time()
    last = LAST_ACTION.get(user_id, 0)
    if now - last < MIN_INTERVAL:
        return True
    LAST_ACTION[user_id] = now
    return False

